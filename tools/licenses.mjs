// NFR-12: list the licences of every production dependency shipped in the client and server; fails on GPL.
//   node tools/licenses.mjs > THIRD_PARTY_LICENSES.md
import { readFileSync, existsSync } from 'node:fs';
const seen = new Map();
const visit = (name, from) => {
  if (seen.has(name)) return;
  let dir = `${from}/node_modules/${name}`;
  if (!existsSync(dir)) dir = `node_modules/${name}`;
  if (!existsSync(`${dir}/package.json`)) return;
  const pkg = JSON.parse(readFileSync(`${dir}/package.json`, 'utf8'));
  const lic = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? 'UNKNOWN';
  seen.set(name, { version: pkg.version, license: lic });
  for (const d of Object.keys(pkg.dependencies ?? {})) visit(d, dir);
};
for (const ws of ['client', 'server', 'engine']) {
  const pkg = JSON.parse(readFileSync(`packages/${ws}/package.json`, 'utf8'));
  for (const d of Object.keys(pkg.dependencies ?? {})) if (!d.startsWith('@tht/')) visit(d, `packages/${ws}`);
}
const rows = [...seen].sort(([a], [b]) => a.localeCompare(b));
const bad = rows.filter(([, v]) => /GPL/i.test(v.license) && !/LGPL/i.test(v.license));
console.log('# Third-party licences\n\nProduction dependencies shipped with Tactical Hex Trainer (generated by `node tools/licenses.mjs`).\n');
console.log('| Package | Version | Licence |\n| --- | --- | --- |');
for (const [n, v] of rows) console.log(`| ${n} | ${v.version} | ${v.license} |`);
if (bad.length) {
  console.error('GPL dependencies found:', bad.map(([n]) => n).join(', '));
  process.exit(1);
}
